export interface CoordHospital {
  ciudad: string
  latitud: number | null
  longitud: number | null
}

// Coordenadas reales si existen, si no aproximadas por ciudad. `exacta: false` cuando es fallback.
export function getCoords(h: CoordHospital): { lat: number; lng: number; exacta: boolean } | null {
  if (h.latitud != null && h.longitud != null) return { lat: h.latitud, lng: h.longitud, exacta: true }
  const c = COORDS_POR_CIUDAD[h.ciudad.toLowerCase().trim()]
  return c ? { lat: c[0], lng: c[1], exacta: false } : null
}
